#!/usr/bin/env python3
"""Write a Markdown status table of the venue profiles: confirmed rules and blocked sources.

    python3 tools/venue_status.py > .claude/skills/paper-check/references/venues/STATUS.md
"""

import sys
from pathlib import Path

import yaml

VENUES = Path(__file__).resolve().parent.parent / ".claude" / "skills" / "paper-check" / "references" / "venues"
GROUP_ORDER = {"general-top5": 0, "general": 1, "field": 2}
GROUP_NAME = {"general-top5": "General, top five", "general": "General", "field": "Field"}


def rules_of(data):
    for key, rule in data["rules"].items():
        if key == "other":
            yield from rule
        else:
            yield rule


def main():
    rows = []
    for path in sorted(VENUES.glob("*.yaml")):
        data = yaml.safe_load(path.read_text())
        rules = list(rules_of(data))
        confirmed = sum(r["status"] == "confirmed" for r in rules)
        blocked = [s for s in data["sources"] if s["access"] == "blocked"]
        rows.append((GROUP_ORDER[data["group"]], data["name"], data, confirmed, len(rules), blocked))
    rows.sort(key=lambda r: (r[0], r[1]))

    out = ["# Venue profile status", "",
           f"Generated by `tools/venue_status.py` from {len(rows)} profiles. Every confirmed rule's quote was "
           "found in its live source by `tools/validate_venues.py --verify-quotes`.", "",
           "| Journal | Group | Checked | Confirmed rules | Pages that blocked automated access |",
           "|---|---|---|---|---|"]
    for _, name, data, confirmed, total, blocked in rows:
        pages = "; ".join(f"[{s['title']}]({s['url']})" for s in blocked) or "None"
        out.append(f"| {name} | {GROUP_NAME[data['group']]} | {data['checked_on']} | {confirmed} of {total} | {pages} |")
    weak = [name for _, name, _, confirmed, total, _ in rows if total and confirmed / total < 0.5]
    out += ["", "## Still to verify", "",
            "These profiles have fewer than half of their rules confirmed, because the journal's own guidelines "
            "refused automated access. Open the blocked pages in a browser, for example with Claude in Chrome in a "
            "session on your own computer, and confirm or correct each unconfirmed rule with a verbatim quote.", ""]
    out += [f"- {name}" for name in weak] or ["- None"]
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
